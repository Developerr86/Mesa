import { Asset } from 'expo-asset';
import { ImageManipulator, SaveFormat } from 'expo-image-manipulator';
import * as jpeg from 'jpeg-js';
import type { TfliteModel } from 'react-native-fast-tflite';
import foodGateClassesJson from './foodGateClasses.json';
import modelLabelsJson from './modelLabels.json';

// Recognition runs in passes, each one only if the previous passed:
//   0. Is the photo usable at all?   pixel statistics, no model
//   1. Is it food?                   MobileNet V1 on ImageNet (Apache-2.0)
//   2. Which dishes?                 Google AIY "food_V1" (MobileNet V1, Apache-2.0)
//
// food_V1 names one dish per image, so pass 2 runs it on the whole photo and on five
// overlapping regions (centre and corners). Separate bowls on a plate or thali each get
// their own look, and the results are merged per dish.
//
// food_V1 takes 192×192 RGB uint8 and returns 2024 uint8-quantized softmax scores.
// modelLabels.json is generated by data/food-db/build_nutrition.py and maps each output
// index to [model label, dish id | null].
const DISH_INPUT_SIZE = 192;
const DISH_OUTPUT_SCALE = 1 / 256;
const DISH_LABELS = modelLabelsJson as [label: string, dishId: string | null][];
const DISH_BACKGROUND_INDEX = 0;

// Pass 1: MobileNet V1 (224×224 RGB uint8 in, 1001 uint8 scores out). The photo counts as
// food when its probability mass on ImageNet's food-related classes (dishes, produce, bread,
// plates and bowls — see foodGateClasses.json) reaches FOOD_THRESHOLD. On test photos, food
// scored 0.55–0.99 and everything else 0.36 or less.
const GATE_INPUT_SIZE = 224;
const GATE_OUTPUT_SCALE = 1 / 256;
const GATE_FOOD_CLASSES = (foodGateClassesJson as [index: number, label: string][]).map(([index]) => index);
const FOOD_THRESHOLD = 0.4;

// Pass 0 thresholds, on 0–255 luminance. Calibrated on real photos: a phone lying face
// down gives a spread of ~2, food photos 50–65, a plain wall ~30, and a heavily
// underexposed but recognisable dish still ~19.
const MIN_CONTRAST = 8;
const DARK_MEAN = 40;

export interface FoodSuggestion {
  label: string; // the model's own label, e.g. "Butter chicken"
  dishId: string | null; // our food database id, when the label maps to one
  confidence: number; // 0–1
}

export type Recognition =
  | { kind: 'unusable'; reason: 'dark' | 'blank' }
  | { kind: 'not_food'; foodScore: number }
  | { kind: 'food'; suggestions: FoodSuggestion[] }; // distinct dishes, best first, at most 6

// Regions of the center square, as [x, y, size] fractions of its side
const REGIONS: [number, number, number][] = [
  [0, 0, 1],
  [0.2, 0.2, 0.6],
  [0, 0, 0.6],
  [0.4, 0, 0.6],
  [0, 0.4, 0.6],
  [0.4, 0.4, 0.6],
];
const MAX_SUGGESTIONS = 6;

const models = new Map<number, Promise<TfliteModel | null>>();

// The TFLite native module only exists in development/production builds. In Expo Go
// models are unavailable and logging stays manual (pass 0 still works).
const loadModel = (source: number) => {
  let model = models.get(source);
  if (!model) {
    model = (async () => {
      try {
        const { loadTensorflowModel } = require('react-native-fast-tflite') as typeof import('react-native-fast-tflite');
        // Resolve the bundled model to a file:// path first. Release builds pack it as an
        // Android raw resource, which fast-tflite can't open from require() directly.
        const [asset] = await Asset.loadAsync(source);
        if (!asset.localUri) {
          throw new Error(`Model asset ${asset.name} could not be resolved to a local file`);
        }
        return await loadTensorflowModel({ url: asset.localUri }, []);
      } catch (error) {
        console.info('Food recognition unavailable:', error instanceof Error ? error.message : error);
        return null;
      }
    })();
    models.set(source, model);
  }
  return model;
};

const DISH_MODEL = require('../../../assets/models/food_v1.tflite') as number;
const GATE_MODEL = require('../../../assets/models/mobilenet_v1_224_quant.tflite') as number;

// Start loading models early, e.g. when the camera opens.
export const warmUpRecognizer = () => {
  loadModel(GATE_MODEL);
  loadModel(DISH_MODEL);
};

// Crops one region of the photo's center square, scales it to `size` and returns the raw
// RGB bytes.
const toRgb = async (
  photoUri: string,
  photo: { width: number; height: number },
  [x, y, fraction]: [number, number, number],
  size: number
): Promise<Uint8Array> => {
  const side = Math.min(photo.width, photo.height);
  const scaled = await ImageManipulator.manipulate(photoUri)
    .crop({
      originX: (photo.width - side) / 2 + x * side,
      originY: (photo.height - side) / 2 + y * side,
      width: fraction * side,
      height: fraction * side,
    })
    .resize({ width: size, height: size })
    .renderAsync();
  const { base64 } = await scaled.saveAsync({ base64: true, format: SaveFormat.JPEG, compress: 1 });
  if (!base64) {
    throw new Error('Image manipulator returned no image data');
  }

  const jpegBytes = Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));
  const { data } = jpeg.decode(jpegBytes, { useTArray: true, formatAsRGBA: false });
  return data;
};

// Pass 0: a near-uniform frame (lens covered, phone face down, blank wall) has nothing to
// recognise, and the food models would still confidently name a dish for it.
const checkUsable = (rgb: Uint8Array): Recognition | null => {
  let sum = 0;
  let sumOfSquares = 0;
  const pixels = rgb.length / 3;
  for (let i = 0; i < rgb.length; i += 3) {
    const luminance = 0.299 * rgb[i] + 0.587 * rgb[i + 1] + 0.114 * rgb[i + 2];
    sum += luminance;
    sumOfSquares += luminance * luminance;
  }
  const mean = sum / pixels;
  const contrast = Math.sqrt(Math.max(0, sumOfSquares / pixels - mean * mean));

  if (contrast >= MIN_CONTRAST) return null;
  return { kind: 'unusable', reason: mean < DARK_MEAN ? 'dark' : 'blank' };
};

// The model wants exactly the input bytes, not a larger backing buffer
const toBuffer = (bytes: Uint8Array) =>
  (bytes.byteOffset === 0 && bytes.byteLength === bytes.buffer.byteLength
    ? bytes.buffer
    : bytes.slice().buffer) as ArrayBuffer;

// Pass 2 for one region: collapses food_V1's scores into dish suggestions. Several model
// labels can map to one dish, so their confidences are summed; unmapped labels are kept by name.
const toSuggestions = (scores: Uint8Array): FoodSuggestion[] => {
  const ranked = Array.from(scores, (score, index) => ({ index, confidence: score * DISH_OUTPUT_SCALE }))
    .filter(({ index }) => index !== DISH_BACKGROUND_INDEX)
    .sort((a, b) => b.confidence - a.confidence)
    .slice(0, 10);

  const byKey = new Map<string, FoodSuggestion>();
  for (const { index, confidence } of ranked) {
    if (confidence < 0.03) break;
    const [label, dishId] = DISH_LABELS[index];
    const key = dishId ?? `label:${label}`;
    const existing = byKey.get(key);
    if (existing) {
      existing.confidence += confidence;
    } else {
      byKey.set(key, { label, dishId, confidence });
    }
  }

  return [...byKey.values()].sort((a, b) => b.confidence - a.confidence).slice(0, 4);
};

// Merges the regions' suggestions: a dish seen in several regions keeps its best confidence.
const mergeSuggestions = (perRegion: FoodSuggestion[][]): FoodSuggestion[] => {
  const best = new Map<string, FoodSuggestion>();
  for (const suggestions of perRegion) {
    for (const suggestion of suggestions) {
      const key = suggestion.dishId ?? `label:${suggestion.label}`;
      const existing = best.get(key);
      if (!existing || suggestion.confidence > existing.confidence) best.set(key, suggestion);
    }
  }
  return [...best.values()].sort((a, b) => b.confidence - a.confidence).slice(0, MAX_SUGGESTIONS);
};

// Pass 1: how much of MobileNet's belief lands on food-related classes.
const scoreFood = async (photoUri: string, photo: { width: number; height: number }): Promise<number | null> => {
  const gateModel = await loadModel(GATE_MODEL);
  if (!gateModel) return null;
  const input = await toRgb(photoUri, photo, REGIONS[0], GATE_INPUT_SIZE);
  const [output] = await gateModel.run([toBuffer(input)]);
  const scores = new Uint8Array(output);
  return GATE_FOOD_CLASSES.reduce((sum, index) => sum + scores[index] * GATE_OUTPUT_SCALE, 0);
};

// Returns null when the photo is usable but the models aren't available (Expo Go) or fail.
// `skipFoodCheck` runs the dish scan even when pass 1 said "not food" (the user insisted).
export const recognizeFood = async (
  photoUri: string,
  { skipFoodCheck = false }: { skipFoodCheck?: boolean } = {}
): Promise<Recognition | null> => {
  try {
    const photo = await ImageManipulator.manipulate(photoUri).renderAsync();
    const [whole, ...parts] = REGIONS;
    const wholeInput = await toRgb(photoUri, photo, whole, DISH_INPUT_SIZE);
    const unusable = checkUsable(wholeInput);
    if (unusable) return unusable;

    if (!skipFoodCheck) {
      const foodScore = await scoreFood(photoUri, photo);
      // Logged in development to tune FOOD_THRESHOLD against real meals
      if (__DEV__) console.info(`Food check score: ${foodScore?.toFixed(2) ?? 'unavailable'}`);
      if (foodScore !== null && foodScore < FOOD_THRESHOLD) return { kind: 'not_food', foodScore };
    }

    const dishModel = await loadModel(DISH_MODEL);
    if (!dishModel) return null;

    const partInputs = await Promise.all(parts.map((region) => toRgb(photoUri, photo, region, DISH_INPUT_SIZE)));
    const perRegion: FoodSuggestion[][] = [];
    for (const input of [wholeInput, ...partInputs]) {
      const [output] = await dishModel.run([toBuffer(input)]);
      perRegion.push(toSuggestions(new Uint8Array(output)));
    }
    return { kind: 'food', suggestions: mergeSuggestions(perRegion) };
  } catch (error) {
    console.warn('Food recognition failed', error);
    return null;
  }
};
